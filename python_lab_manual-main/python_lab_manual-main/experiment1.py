# Demonstration of different data types

integer = 10
float = 10.5
complex = 2 + 3j
string = "Python"
boolean = True
list = [1, 2, 3]
tuple = (1, 2, 3)

print("Integer:", integer)
print("Float:", float)
print("Complex:", complex)
print("String:",string )
print("Boolean:", boolean)
print("List:", list)
print("Tuple:", tuple)

# Demonstration of built-in functions

print("\nBuilt-in Functions:")

# abs()
number = -15
print("Value:", number)
print("Absolute value:", abs(number))

# len()
string = "Python"
print("\nString:", string)
print("Length:", len(string))

# min()
numbers = [10, 5, 20, 3]
print("\nNumbers:", numbers)
print("Minimum value:", min(numbers))

# round()
number = 12.5678
print("\nValue:", number)
print("Rounded value:", round(number, 2))

# isalnum()
string = "Python123"
print("\nString:", string)
print("Is alphanumeric?:", string.isalnum())

# type()
value = 25
print("\nValue:", value)
print("Data type:", type(value))


